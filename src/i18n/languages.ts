/**
 * Языки приложения — одним списком.
 *
 * Раньше их было три, и они были переписаны в двух местах: в настройке
 * i18next и в переключателе. Пока языков три, это терпимо; когда их
 * восемь, два списка однажды разойдутся — в одном язык будет, в другом
 * нет, и человек увидит пустую кнопку или язык без словаря.
 *
 * Поэтому список один, и всё остальное читает его.
 */

export type Language = {
  /** Код языка, он же имя файла словаря. */
  code: string;

  /**
   * Название на самом языке.
   *
   * Не «украинский», а «Українська»: человек ищет свой язык глазами, и
   * ищет его написанным так, как привык. Переводить названия языков —
   * значит прятать нужный от того, кому он нужен.
   */
  name: string;

  /**
   * Словарь переведён и язык можно предлагать.
   *
   * Пока ложь — язык подключён, файл существует, но в списке выбора
   * его нет. Так перевод можно выкатывать частями, не показывая
   * человеку полупустой кабинет.
   */
  ready: boolean;
};

/**
 * Румынский — язык площадки и последнее прибежище.
 *
 * Отдельным именем он назван затем, что на него опирается выбор, когда
 * в хранилище браузера лежит язык, которого в списке уже нет.
 */
export const DEFAULT_LANGUAGE: Language = {
  code: 'ro',
  name: 'Română',
  ready: true,
};

export const LANGUAGES: Language[] = [
  { code: 'ru', name: 'Русский', ready: true },
  DEFAULT_LANGUAGE,
  { code: 'en', name: 'English', ready: true },
  { code: 'uk', name: 'Українська', ready: true },
  { code: 'pl', name: 'Polski', ready: true },
  { code: 'it', name: 'Italiano', ready: true },
  { code: 'es', name: 'Español', ready: false },
  { code: 'fr', name: 'Français', ready: false },
];

/** Те, что можно предлагать человеку прямо сейчас. */
export const READY_LANGUAGES = LANGUAGES.filter((one) => one.ready);

/** Все коды — i18next должен знать и о недоделанных. */
export const LANGUAGE_CODES = LANGUAGES.map((one) => one.code);

/**
 * Чем подменять непереведённую строку.
 *
 * Не пустотой и не ключом. Украинцу понятнее русский, остальным —
 * английский; последним рубежом стоит румынский, язык площадки.
 * Цепочка нужна именно на время перевода: пока раздел не переведён,
 * человек видит осмысленный текст, а не `nav.clients`.
 */
export const FALLBACK: Record<string, string[]> = {
  uk: ['ru', 'ro'],
  pl: ['en', 'ro'],
  it: ['en', 'ro'],
  es: ['en', 'ro'],
  fr: ['en', 'ro'],
  default: ['ro'],
};


/**
 * В каком порядке пробовать языки.
 *
 * Сначала свой, потом цепочка подмен, последним — язык площадки.
 * Повторов нет: одно и то же не пробуется дважды.
 *
 * Спрашивают этот порядок не только словари i18next. Правовые тексты
 * и подписи подвала лежат отдельно и переведены не на все языки —
 * пусть отступают туда же, куда и остальное, а не каждый по-своему.
 */
export function languageOrder(language?: string | null): string[] {
  const wanted = (language ?? '').slice(0, 2).toLowerCase();
  const chain = FALLBACK[wanted] ?? FALLBACK.default;
  const order: string[] = [];

  for (const code of [wanted, ...chain, DEFAULT_LANGUAGE.code]) {
    if (code && !order.includes(code)) {
      order.push(code);
    }
  }

  return order;
}
